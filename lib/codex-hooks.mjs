#!/usr/bin/env node
/**
 * Manage ctx-kit's project-local Codex hooks without touching Claude's
 * settings.local.json or a user's unrelated Codex hook handlers.
 *
 * The generated runner deliberately contains absolute paths: Codex hooks run
 * outside an interactive shell, so relying on PATH makes an otherwise valid
 * context-mode or code-graph installation silently disappear.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const argv = process.argv.slice(2);
const mode = argv[0];
const value = (name, fallback = '') => {
  const index = argv.indexOf(`--${name}`);
  return index >= 0 && argv[index + 1] ? argv[index + 1] : fallback;
};

if (!['apply', 'remove'].includes(mode)) {
  console.error('usage: codex-hooks.mjs <apply|remove> --project-dir DIR [--node PATH --context-cli PATH --code-graph PATH --throttle SEC]');
  process.exit(2);
}

const projectDir = value('project-dir');
if (!projectDir) {
  console.error('missing --project-dir');
  process.exit(2);
}
const throttle = Number.parseInt(value('throttle', '120'), 10);
if (!Number.isFinite(throttle) || throttle < 0) {
  console.error('invalid --throttle');
  process.exit(2);
}

const codexDir = join(projectDir, '.codex');
const hooksDir = join(codexDir, 'hooks');
const hooksPath = join(codexDir, 'hooks.json');
const runnerBase = 'ctx-kit-codex';
const runnerPs = join(hooksDir, `${runnerBase}.ps1`);
const runnerSh = join(hooksDir, `${runnerBase}.sh`);
const marker = runnerBase;

function readHooks() {
  if (!existsSync(hooksPath)) return { hooks: {} };
  let parsed;
  try {
    parsed = JSON.parse(readFileSync(hooksPath, 'utf8'));
  } catch (error) {
    console.error(`refusing to modify malformed JSON: ${hooksPath}\n  ${error.message}`);
    process.exit(1);
  }
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    console.error(`refusing to modify non-object JSON: ${hooksPath}`);
    process.exit(1);
  }
  parsed.hooks = parsed.hooks && typeof parsed.hooks === 'object' ? parsed.hooks : {};
  return parsed;
}

function isOurs(handler) {
  return String(handler?.command || '').includes(marker) || String(handler?.commandWindows || '').includes(marker) ||
    String(handler?.command || '').includes('context-policy.mjs') || String(handler?.commandWindows || '').includes('context-policy.mjs');
}

function removeOurs(config) {
  for (const [event, groups] of Object.entries(config.hooks || {})) {
    if (!Array.isArray(groups)) continue;
    const kept = groups
      .map((group) => ({ ...group, hooks: (group.hooks || []).filter((handler) => !isOurs(handler)) }))
      .filter((group) => group.hooks.length > 0);
    if (kept.length) config.hooks[event] = kept;
    else delete config.hooks[event];
  }
  if (Object.keys(config.hooks).length === 0) delete config.hooks;
}

function psQuote(value) {
  return `\"${String(value).replace(/\"/g, '\\\"')}\"`;
}

function commandFor(action, isAsync = false) {
  const sh = `sh \"${runnerSh.replace(/\\/g, '/')}\" --action ${action}`;
  const ps = `powershell.exe -NoProfile -NonInteractive -ExecutionPolicy Bypass -File ${psQuote(runnerPs)} -Action ${action}`;
  return {
    type: 'command',
    command: sh,
    commandWindows: ps,
    ...(isAsync ? { async: true, timeout: 120 } : {}),
  };
}

function group(matcher, handlers) {
  return { ...(matcher ? { matcher } : {}), hooks: handlers };
}

function writeRunners({ nodePath, contextCli, codeGraph }) {
  mkdirSync(hooksDir, { recursive: true });
  const ps = `# Generated by ctx-kit. Edit the installer inputs, not this file.\n[CmdletBinding()]param([Parameter(Mandatory=$true)][string]$Action)\n$ErrorActionPreference='Continue'\n$Node=${psQuote(nodePath)}\n$ContextCli=${psQuote(contextCli)}\n$CodeGraph=${psQuote(codeGraph)}\n$Project=${psQuote(projectDir)}\n$Stamp=Join-Path $Project '.code-graph\\.auto-index-stamp'\nfunction Invoke-Context([string]$Event){ & { $input } | & $Node $ContextCli hook codex $Event; exit $LASTEXITCODE }\nfunction Invoke-Index([bool]$Throttled){ if(-not (Test-Path (Join-Path $Project '.code-graph'))){exit 0}; if($Throttled){$now=[DateTimeOffset]::UtcNow.ToUnixTimeSeconds();$last=0;if(Test-Path $Stamp){[void][Int64]::TryParse((Get-Content $Stamp -Raw).Trim(),[ref]$last)};if(($now-$last)-lt ${throttle}){exit 0};Set-Content -Path $Stamp -Value $now -NoNewline -Encoding ascii}else{Set-Content -Path $Stamp -Value ([DateTimeOffset]::UtcNow.ToUnixTimeSeconds()) -NoNewline -Encoding ascii};Push-Location $Project; & $CodeGraph incremental-index --quiet *> $null; Pop-Location; exit 0 }\nswitch($Action){'context-pretooluse'{Invoke-Context 'pretooluse'}'context-posttooluse'{Invoke-Context 'posttooluse'}'context-sessionstart'{Invoke-Context 'sessionstart'}'context-precompact'{Invoke-Context 'precompact'}'context-userpromptsubmit'{Invoke-Context 'userpromptsubmit'}'context-stop'{Invoke-Context 'stop'}'index-sessionstart'{Invoke-Index $false}'index-write'{Invoke-Index $false}'index-prompt'{Invoke-Index $true}default{exit 2}}\n`;
  const sh = `#!/usr/bin/env sh\n# Generated by ctx-kit. Edit the installer inputs, not this file.\nACTION=\"\"\n[ \"$1\" = \"--action\" ] && ACTION=\"$2\"\nNODE=${JSON.stringify(nodePath)}\nCONTEXT_CLI=${JSON.stringify(contextCli)}\nCODE_GRAPH=${JSON.stringify(codeGraph)}\nPROJECT=${JSON.stringify(projectDir.replace(/\\/g, '/'))}\nSTAMP=\"$PROJECT/.code-graph/.auto-index-stamp\"\ncontext(){ \"$NODE\" \"$CONTEXT_CLI\" hook codex \"$1\"; }\nindex(){ [ -d \"$PROJECT/.code-graph\" ] || exit 0; if [ \"$1\" = throttled ]; then now=$(date +%s); last=$(cat \"$STAMP\" 2>/dev/null || echo 0); [ $((now-last)) -ge ${throttle} ] || exit 0; printf '%s' \"$now\" > \"$STAMP\"; else date +%s > \"$STAMP\"; fi; (cd \"$PROJECT\" && \"$CODE_GRAPH\" incremental-index --quiet) >/dev/null 2>&1; }\ncase \"$ACTION\" in context-pretooluse) context pretooluse;; context-posttooluse) context posttooluse;; context-sessionstart) context sessionstart;; context-precompact) context precompact;; context-userpromptsubmit) context userpromptsubmit;; context-stop) context stop;; index-sessionstart|index-write) index now;; index-prompt) index throttled;; *) exit 2;; esac\n`;
  writeFileSync(runnerPs, ps, 'utf8');
  writeFileSync(runnerSh, sh, { encoding: 'utf8', mode: 0o755 });
}

const config = readHooks();
removeOurs(config);
if (mode === 'apply') {
  const nodePath = value('node');
  const contextCli = value('context-cli');
  const codeGraph = value('code-graph');
  if (!nodePath || !contextCli || !codeGraph) {
    console.error('apply requires --node, --context-cli, and --code-graph');
    process.exit(2);
  }
  writeRunners({ nodePath, contextCli, codeGraph });
  const hooks = config.hooks = config.hooks || {};
  const add = (event, matcher, handler) => {
    hooks[event] = hooks[event] || [];
    hooks[event].push(group(matcher, [handler]));
  };
  const contextMatchers = 'local_shell|shell|shell_command|exec_command|Bash|Shell|apply_patch|Edit|Write|grep_files|ctx_execute|ctx_execute_file|ctx_batch_execute|ctx_fetch_and_index|ctx_search|ctx_index|mcp__';
  add('PreToolUse', contextMatchers, commandFor('context-pretooluse'));
  add('PostToolUse', '.*', commandFor('context-posttooluse'));
  add('SessionStart', 'startup|resume|clear|compact', commandFor('context-sessionstart'));
  add('PreCompact', 'manual|auto', commandFor('context-precompact'));
  add('UserPromptSubmit', '', commandFor('context-userpromptsubmit'));
  add('Stop', '', commandFor('context-stop'));
  add('SessionStart', 'startup|resume|clear|compact', commandFor('index-sessionstart', true));
  add('PostToolUse', '^(apply_patch|Edit|Write)$', commandFor('index-write', true));
  add('UserPromptSubmit', '', commandFor('index-prompt', true));
}

mkdirSync(dirname(hooksPath), { recursive: true });
writeFileSync(hooksPath, JSON.stringify(config, null, 2) + '\n');
console.log(hooksPath);
